# Recursive-descent Z80 code finder: a lower bound on what is code.
import sys
L2 = set([0x06,0x0E,0x16,0x1E,0x26,0x2E,0x36,0x3E,0xC6,0xCE,0xD6,0xDE,0xE6,0xEE,0xF6,0xFE,0xD3,0xDB,0x10,0x18,0x20,0x28,0x30,0x38,0xCB])
L3 = set([0x01,0x11,0x21,0x31,0x22,0x2A,0x32,0x3A,0xC2,0xC3,0xCA,0xD2,0xDA,0xE2,0xEA,0xF2,0xFA,0xC4,0xCC,0xCD,0xD4,0xDC,0xE4,0xEC,0xF4,0xFC])
HLIND = set([0x34,0x35,0x46,0x4E,0x56,0x5E,0x66,0x6E,0x7E,0x70,0x71,0x72,0x73,0x74,0x75,0x77,0x86,0x8E,0x96,0x9E,0xA6,0xAE,0xB6,0xBE])
def decode(m, a):
    """return (length, kind, target) kind: 'jp','jpc','call','ret','retc','ind','rst','seq'"""
    op = m[a]
    w = lambda o: m[(a+o)&0xFFFF] | m[(a+o+1)&0xFFFF]<<8
    rel = lambda: (a + 2 + ((m[(a+1)&0xFFFF]^0x80)-0x80)) & 0xFFFF
    if op == 0xED:
        o2 = m[(a+1)&0xFFFF]
        if o2 in (0x43,0x4B,0x53,0x5B,0x63,0x6B,0x73,0x7B): return 4,'seq',None
        if o2 in (0x45,0x4D,0x55,0x5D,0x65,0x6D,0x75,0x7D): return 2,'ret',None
        return 2,'seq',None
    if op in (0xDD,0xFD):
        o2 = m[(a+1)&0xFFFF]
        if o2 == 0xCB: return 4,'seq',None
        if o2 == 0xE9: return 2,'ind',None
        if o2 in (0x21,0x22,0x2A): return 4,'seq',None
        if o2 == 0x36: return 4,'seq',None
        if o2 in HLIND: return 3,'seq',None
        if o2 in (0xDD,0xFD,0xED): return 1,'seq',None
        if o2 in L2: return 3,'seq',None
        if o2 in L3: return 4,'seq',None
        return 2,'seq',None
    if op == 0xC3: return 3,'jp',w(1)
    if op in (0xC2,0xCA,0xD2,0xDA,0xE2,0xEA,0xF2,0xFA): return 3,'jpc',w(1)
    if op == 0xCD: return 3,'call',w(1)
    if op in (0xC4,0xCC,0xD4,0xDC,0xE4,0xEC,0xF4,0xFC): return 3,'call',w(1)
    if op == 0x18: return 2,'jp',rel()
    if op in (0x10,0x20,0x28,0x30,0x38): return 2,'jpc',rel()
    if op == 0xC9: return 1,'ret',None
    if op in (0xC0,0xC8,0xD0,0xD8,0xE0,0xE8,0xF0,0xF8): return 1,'seq',None
    if op == 0xE9: return 1,'ind',None
    if op in (0xC7,0xCF,0xD7,0xDF,0xE7,0xEF,0xF7,0xFF): return 1,'call',op&0x38
    if op in L2: return 2,'seq',None
    if op in L3: return 3,'seq',None
    return 1,'seq',None
def trace(m, entries, lo, hi):
    code = bytearray(65536); seen = set(); todo = list(entries); calls=set(); indirect=[]
    while todo:
        a = todo.pop()
        while lo <= a < hi and a not in seen:
            seen.add(a)
            n,k,t = decode(m,a)
            for i in range(n): code[(a+i)&0xFFFF] = 1
            if k in ('jp','jpc','call') and t is not None:
                todo.append(t)
                if k=='call': calls.add(t)
            if k in ('jp','ret','ind'):
                if k=='ind': indirect.append(a)
                break
            a = (a+n)&0xFFFF
    return code, calls, indirect
